# Verify hack/gen-chaos-matrix.sh and the tables it generates on the chaos
# page, docs/reference/testing/chaos-e2e-tests.md.
#
# On a fixture tree (CHAOS_SUITES_DIR, CHAOS_PAGE):
#   - the matrix has one row per component in vocabulary order, empty rows
#     included, a cell joins its suites with <br> in suite order, and the
#     suite table carries the scenario, the component/role pairs and the
#     budget; a second run changes nothing and --check passes;
#   - --check on a changed header prints the diff -u and fails naming the
#     stale page, which it leaves untouched;
#   - a suite without a matrix line, a matrix line with two fields, an
#     unknown component, role or kind, two scenario lines, SC-CHAOS-9, two
#     suites sharing an ID, a missing BEGIN or END marker, END before BEGIN and
#     an empty suites directory each fail with their FAIL line, naming
#     <file>:<line> where there is one, and leave the page byte-identical.
#
# check_scenarios compares the `# Chaos scenario:` line of every suite header
# with the first `**Scenario:**` line of the suite's `### <suite>` section: a
# section naming SC-CHAOS-NNN while the header names none, and two different
# IDs, are reported.
#
# On the repository: --check passes, the scenarios agree, no bare SC-CHAOS
# line is left, every suite carries a matrix line, and the matrix has its 23
# rows with flux, hypervisor-operator and kvm-node-agent empty.
#
# Usage: bash tests/unit/docs/chaos_matrix_test.sh

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
GEN="$PROJECT_ROOT/hack/gen-chaos-matrix.sh"
REPO_PAGE="$PROJECT_ROOT/docs/reference/testing/chaos-e2e-tests.md"

PASS=0
FAIL=0
SKIP=0

# shellcheck source=tests/lib/assertions.sh
source "$PROJECT_ROOT/tests/lib/assertions.sh"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

BEGIN_MARKER='<!-- BEGIN chaos-matrix: generated by hack/gen-chaos-matrix.sh, do not edit -->'
END_MARKER='<!-- END chaos-matrix -->'
COMPONENTS="keystone horizon glance placement barbican neutron ovn cinder nova controlplane k-orc mariadb memcached rabbitmq openbao garage nfs cert-manager external-secrets envoy-gateway flux hypervisor-operator kvm-node-agent"
EMPTY_ROW_CELLS="| — | — | — | — | — | — | — |"
TAB="$(printf '\t')"

# Print one line per suite whose header scenario and page scenario differ:
# the suite, a tab, the header's ID (or "none") and the page's (or "none").
# The page's ID is the SC-CHAOS-NNN token of the first **Scenario:** line of
# the `### <suite>` section.
# shellcheck disable=SC2016 # an awk program, not shell
PAGE_SCENARIOS_AWK='
/^###? / { section = ""; if (substr($0, 1, 4) == "### ") section = substr($0, 5); next }
section != "" && !(section in seen) && index($0, "**Scenario:**") == 1 {
  seen[section] = 1
  id = ""
  if (match($0, /SC-CHAOS-[0-9][0-9][0-9]/)) id = substr($0, RSTART, RLENGTH)
  print section "\t" id
}
'

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# check_scenarios <suites-dir> <page>
check_scenarios() {
  local dir="$1" page="$2" file suite header on_page scenarios
  scenarios="$(awk "$PAGE_SCENARIOS_AWK" "$page")"
  for file in "$dir"/*/chainsaw-test.yaml; do
    [ -f "$file" ] || continue
    suite="$(basename "$(dirname "$file")")"
    header="$(awk '!/^#/ && !/^[ \t]*$/ { exit } /^# Chaos scenario:/ { print $4; exit }' "$file")"
    on_page="$(awk -F'\t' -v s="$suite" '$1 == s { print $2; exit }' <<<"$scenarios")"
    if [ "$header" != "$on_page" ]; then
      printf '%s\t%s\t%s\n' "$suite" "${header:-none}" "${on_page:-none}"
    fi
  done
}

# gen <suites-dir> <page> [--check] — run the generator on a fixture; OUT
# holds stdout and stderr, RC the exit code.
gen() {
  local dir="$1" page="$2"
  shift 2
  RC=0
  OUT="$(CHAOS_SUITES_DIR="$dir" CHAOS_PAGE="$page" bash "$GEN" "$@" 2>&1)" || RC=$?
}

# suite <dir> <name> <header-line...> — write a suite whose header holds the
# SPDX block and the given lines.
suite() {
  local dir="$1" name="$2"
  shift 2
  mkdir -p "$dir/$name"
  {
    echo "# SPDX-FileCopyrightText: Copyright 2026 SAP SE or an SAP affiliate company"
    echo "#"
    echo "# SPDX-License-Identifier: Apache-2.0"
    echo ""
    echo "# Chainsaw chaos E2E test $name."
    printf '%s\n' "$@"
    echo "apiVersion: chainsaw.kyverno.io/v1alpha1"
    echo "kind: Test"
    echo "# Chaos matrix: flux self pod-kill"
  } >"$dir/$name/chainsaw-test.yaml"
}

# fixture <root> — a suites tree of three suites and a page with the markers.
fixture() {
  local root="$1"
  rm -rf "$root"
  mkdir -p "$root/suites"
  suite "$root/suites" b-two \
    "# Chaos matrix: mariadb self partition" \
    "# Chaos matrix: keystone self partition" \
    "# Chaos budget: failures=40 recovery=90s" \
    "# Chaos budget measured: 2026-10-15, estimate, failures 20, recovery 60 s"
  suite "$root/suites" a-one \
    "# Chaos scenario: SC-CHAOS-001" \
    "#" \
    "# Chaos matrix: keystone self pod-kill" \
    "# Chaos budget: failures=0 recovery=0s"
  suite "$root/suites" c-three \
    "# Chaos matrix: cinder backend scale-to-zero"
  {
    echo "# Chaos page"
    echo ""
    echo "## Test Suite Inventory"
    echo ""
    echo "$BEGIN_MARKER"
    echo "stale"
    echo "$END_MARKER"
    echo ""
    echo "## Test Suite Details"
  } >"$root/page.md"
}

# expect_fail <name> <root> <want-line> — run the generator on the fixture
# under root, and assert exit 1, the FAIL line and an untouched page.
expect_fail() {
  local name="$1" root="$2" want="$3"
  cp "$root/page.md" "$root/page.before"
  gen "$root/suites" "$root/page.md"
  assert_eq "$name: exits 1" "1" "$RC"
  assert_contains "$name: names the problem" "$OUT" "$want"
  if cmp -s "$root/page.md" "$root/page.before"; then
    echo "  PASS: $name: the page is byte-identical"
    PASS=$((PASS + 1))
  else
    echo "  FAIL: $name: the page changed"
    FAIL=$((FAIL + 1))
  fi
}

# matrix_rows <page> — the rows of the matrix table, one per line.
matrix_rows() {
  awk -v b="$BEGIN_MARKER" -v e="$END_MARKER" '
    $0 == b { in_block = 1; next }
    $0 == e { exit }
    in_block && /^\| Component \|/ { in_matrix = 1; next }
    in_matrix && /^\| --- / { next }
    in_matrix && /^\|/ { print; next }
    in_matrix { exit }
  ' "$1"
}

# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------

test_the_generated_tables() {
  echo "Test: the generator renders the matrix and the suite table"
  local root="$TMP_DIR/gen" rows names
  fixture "$root"

  gen "$root/suites" "$root/page.md"
  assert_eq "it exits 0" "0" "$RC"
  rows="$(matrix_rows "$root/page.md")"
  assert_eq "23 rows" "23" "$(grep -c . <<<"$rows")"
  names="$(sed 's/^| \([^ ]*\) |.*/\1/' <<<"$rows" | paste -sd' ' -)"
  assert_eq "the rows follow the vocabulary" "$COMPONENTS" "$names"
  assert_eq "an empty row keeps its place" "| flux $EMPTY_ROW_CELLS" "$(grep '^| flux |' <<<"$rows")"
  assert_contains "a cell joins its suites with <br> in suite order" "$rows" \
    "| keystone | — | [a-one](#a-one) (pod-kill)<br>[b-two](#b-two) (partition) | — |"
  assert_contains "a platform row names the suite that hits it" "$rows" \
    "| mariadb | — | [b-two](#b-two) (partition) |"
  assert_contains "a backend cell" "$rows" \
    "| cinder | — | — | — | — | — | — | [c-three](#c-three) (scale-to-zero) |"
  assert_file_contains_fixed "the suite table has its header" "$root/page.md" \
    "| Suite | Scenario ID | Matrix | Budget |"
  assert_file_contains_fixed "a suite with a scenario and a budget" "$root/page.md" \
    '| [a-one](#a-one) | SC-CHAOS-001 | `keystone/self` | failures=0 recovery=0s |'
  assert_file_contains_fixed "the pairs follow the header order" "$root/page.md" \
    '| [b-two](#b-two) | — | `mariadb/self`, `keystone/self` | failures=40 recovery=90s |'
  assert_file_contains_fixed "a suite without a scenario or a budget" "$root/page.md" \
    '| [c-three](#c-three) | — | `cinder/backend` | — |'
  assert_file_not_contains "the stale content is gone" "$root/page.md" "^stale$"
  assert_file_not_contains "a matrix line below the header is not read" "$root/page.md" "flux.*pod-kill"
  assert_file_contains_fixed "the text after the markers is kept" "$root/page.md" "## Test Suite Details"

  cp "$root/page.md" "$root/page.first"
  gen "$root/suites" "$root/page.md"
  if cmp -s "$root/page.md" "$root/page.first"; then
    echo "  PASS: a second run changes nothing"
    PASS=$((PASS + 1))
  else
    echo "  FAIL: a second run changed the page"
    FAIL=$((FAIL + 1))
  fi
  gen "$root/suites" "$root/page.md" --check
  assert_eq "--check passes on the generated page" "0" "$RC"
}

test_a_stale_page_fails_the_check() {
  echo "Test: --check on a changed header prints the diff and names the stale page"
  local root="$TMP_DIR/stale"
  fixture "$root"
  gen "$root/suites" "$root/page.md"
  sed -i.bak 's/^# Chaos matrix: keystone self pod-kill$/# Chaos matrix: keystone cache pod-kill/' \
    "$root/suites/a-one/chainsaw-test.yaml"
  cp "$root/page.md" "$root/page.before"

  gen "$root/suites" "$root/page.md" --check
  assert_eq "it exits 1" "1" "$RC"
  assert_contains "it prints the diff" "$OUT" "+| keystone | — | [b-two](#b-two) (partition) | — | — | [a-one](#a-one) (pod-kill) | — | — |"
  assert_contains "it names the stale page" "$OUT" "FAIL: $root/page.md is stale; run make gen-chaos-matrix"
  if cmp -s "$root/page.md" "$root/page.before"; then
    echo "  PASS: the page is left as it was"
    PASS=$((PASS + 1))
  else
    echo "  FAIL: --check changed the page"
    FAIL=$((FAIL + 1))
  fi
}

test_an_invalid_header_fails() {
  local root="$TMP_DIR/bad" f
  echo "Test: invalid headers fail before the page is written"

  fixture "$root"
  f="$root/suites/c-three/chainsaw-test.yaml"
  sed -i.bak '/^# Chaos matrix: cinder/d' "$f"
  expect_fail "a suite without a matrix line" "$root" \
    "FAIL: $f:6: the header ends here without a \"# Chaos matrix:\" line"

  fixture "$root"
  sed -i.bak 's/^# Chaos matrix: cinder backend scale-to-zero$/# Chaos matrix: cinder backend/' "$f"
  expect_fail "a line with two fields" "$root" \
    "FAIL: $f:6: \"# Chaos matrix: cinder backend\": want \"# Chaos matrix: <component> <role> <kind>\""

  fixture "$root"
  sed -i.bak 's/^# Chaos matrix: cinder /# Chaos matrix: manila /' "$f"
  expect_fail "an unknown component" "$root" \
    "FAIL: $f:6: \"# Chaos matrix: manila backend scale-to-zero\": unknown component \"manila\""

  fixture "$root"
  sed -i.bak 's/^# Chaos matrix: cinder backend /# Chaos matrix: cinder storage /' "$f"
  expect_fail "an unknown role" "$root" \
    "FAIL: $f:6: \"# Chaos matrix: cinder storage scale-to-zero\": unknown role \"storage\""

  fixture "$root"
  sed -i.bak 's/ scale-to-zero$/ disk-fill/' "$f"
  expect_fail "an unknown kind" "$root" \
    "FAIL: $f:6: \"# Chaos matrix: cinder backend disk-fill\": unknown kind \"disk-fill\""

  fixture "$root"
  f="$root/suites/a-one/chainsaw-test.yaml"
  sed -i.bak '7s/^#$/# Chaos scenario: SC-CHAOS-002/' "$f"
  expect_fail "two scenario lines" "$root" \
    "FAIL: $f:7: \"# Chaos scenario: SC-CHAOS-002\": a second \"# Chaos scenario:\" line"

  fixture "$root"
  sed -i.bak 's/^# Chaos scenario: SC-CHAOS-001$/# Chaos scenario: SC-CHAOS-9/' "$f"
  expect_fail "SC-CHAOS-9" "$root" \
    "FAIL: $f:6: \"# Chaos scenario: SC-CHAOS-9\": want SC-CHAOS-NNN"

  fixture "$root"
  f="$root/suites/b-two/chainsaw-test.yaml"
  awk '/^# Chaos matrix: mariadb self partition$/ { print "# Chaos scenario: SC-CHAOS-001" } { print }' \
    "$f" >"$f.tmp" && mv "$f.tmp" "$f"
  expect_fail "two suites sharing an ID" "$root" \
    "FAIL: $f:6: \"# Chaos scenario: SC-CHAOS-001\": SC-CHAOS-001 is also the scenario of a-one"
}

test_a_broken_page_or_tree_fails() {
  local root="$TMP_DIR/page"
  echo "Test: missing markers and an empty suites directory fail"

  fixture "$root"
  grep -vxF "$BEGIN_MARKER" "$root/page.md" >"$root/page.tmp" && mv "$root/page.tmp" "$root/page.md"
  expect_fail "a missing BEGIN marker" "$root" "FAIL: $root/page.md: no line \"$BEGIN_MARKER\""

  fixture "$root"
  grep -vxF "$END_MARKER" "$root/page.md" >"$root/page.tmp" && mv "$root/page.tmp" "$root/page.md"
  expect_fail "a missing END marker" "$root" "FAIL: $root/page.md: no line \"$END_MARKER\""

  fixture "$root"
  printf '%s\n' "$END_MARKER" "x" "$BEGIN_MARKER" >"$root/page.md"
  expect_fail "END before BEGIN" "$root" "FAIL: $root/page.md:1: \"$END_MARKER\" comes before"

  fixture "$root"
  rm -rf "$root/suites"
  mkdir -p "$root/suites/lib"
  expect_fail "an empty suites directory" "$root" "FAIL: no suite under $root/suites"
}

test_scenarios_agree_with_the_page() {
  local root="$TMP_DIR/scen"
  echo "Test: check_scenarios compares each header with its page section"
  fixture "$root"
  {
    echo "### a-one"
    echo ""
    echo "**Scenario:** SC-CHAOS-001"
    echo ""
    echo "### b-two"
    echo ""
    echo "**Scenario:** SC-CHAOS-009"
    echo ""
    echo "### c-three"
    echo ""
    echo "**Scenario:** none"
  } >>"$root/page.md"

  assert_eq "a section naming an ID the header lacks is reported" \
    "b-two${TAB}none${TAB}SC-CHAOS-009" "$(check_scenarios "$root/suites" "$root/page.md")"

  sed -i.bak 's/^\*\*Scenario:\*\* SC-CHAOS-001$/**Scenario:** SC-CHAOS-004/' "$root/page.md"
  assert_contains "two different IDs are reported" \
    "$(check_scenarios "$root/suites" "$root/page.md")" "a-one${TAB}SC-CHAOS-001${TAB}SC-CHAOS-004"

  sed -i.bak -e 's/^\*\*Scenario:\*\* SC-CHAOS-004$/**Scenario:** SC-CHAOS-001/' \
    -e 's/^\*\*Scenario:\*\* SC-CHAOS-009$/**Scenario:** none/' "$root/page.md"
  assert_eq "agreeing scenarios report nothing" "" "$(check_scenarios "$root/suites" "$root/page.md")"
}

test_the_repository() {
  echo "Test: the repository's chaos page is current"
  local rows total zero

  RC=0
  OUT="$(bash "$GEN" --check 2>&1)" || RC=$?
  assert_eq "hack/gen-chaos-matrix.sh --check passes" "0" "$RC"
  assert_eq "every header scenario matches its section" "" \
    "$(check_scenarios "$PROJECT_ROOT/tests/e2e-chaos" "$REPO_PAGE")"
  assert_eq "no bare SC-CHAOS line is left" "" \
    "$(grep -l '^# SC-CHAOS' "$PROJECT_ROOT"/tests/e2e-chaos/*/chainsaw-test.yaml)"
  zero="$(grep -c '^# Chaos matrix:' "$PROJECT_ROOT"/tests/e2e-chaos/*/chainsaw-test.yaml | grep -c ':0$')"
  assert_eq "every suite carries a matrix line" "0" "$zero"
  total="$(cat "$PROJECT_ROOT"/tests/e2e-chaos/*/chainsaw-test.yaml | grep -c '^# Chaos matrix:')"
  assert_gte "the suites carry matrix lines" "$total" 1

  rows="$(matrix_rows "$REPO_PAGE")"
  assert_eq "the matrix has 23 rows" "23" "$(grep -c . <<<"$rows")"
  local name
  for name in flux hypervisor-operator kvm-node-agent; do
    assert_eq "$name keeps an empty row" "| $name $EMPTY_ROW_CELLS" "$(grep "^| $name |" <<<"$rows")"
  done
}

# ---------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------
test_the_generated_tables
test_a_stale_page_fails_the_check
test_an_invalid_header_fails
test_a_broken_page_or_tree_fails
test_scenarios_agree_with_the_page
test_the_repository

echo ""
echo "Results: $PASS passed, $FAIL failed, $SKIP skipped"
if [ "$FAIL" -gt 0 ]; then
  exit 1
fi
exit 0
