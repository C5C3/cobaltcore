# nix/spike/generate-lock.sh — Translate the release pins of one service into
# the inputs the Nix spike builds its Python environment from.
#
# Usage, from the repository root:
#   bash nix/spike/generate-lock.sh <service> <release>
#   bash nix/spike/generate-lock.sh keystone 2026.1
#
# Writes nix/spike/locks/<release>/<service>/:
#   sources.json    the ref releases/<release>/source-refs.yaml pins, the
#                   commit that ref names and the NAR hash of its tree, and
#                   the repo-relative paths of patches/<service>/<release>/*.patch;
#                   the build fetches by commit and hash, never through the tag
#   pyproject.toml  a virtual uv project: the service as a git source at that
#                   commit with its pip_extras, the pip_packages of
#                   releases/<release>/extra-packages.yaml, the venv-builder
#                   pins, the merged constraints as constraint-dependencies,
#                   and a test dependency group
#   uv.lock         what `uv lock` resolves from pyproject.toml
#
# The three files are committed and regenerated by hand (README.md, D2). The
# tracked releases/ and overrides/ files are only read: the constraint
# overrides are merged into a temporary copy by
# scripts/apply-constraint-overrides.sh. The files move into place only after
# `uv lock` succeeded, so a failed run leaves the previous lock untouched.
# A release patch that edits requirements.txt or test-requirements.txt is
# refused: the lock is resolved from the upstream files.
#
# Requires uv, nix (with the nix-command and flakes features), yq (mikefarah)
# and jq on PATH. `nix flake prefetch github:...` calls the GitHub API; set
# `access-tokens = github.com=<token>` in nix.conf if unauthenticated runs hit
# its rate limit.

set -euo pipefail

usage() {
  echo "Usage: $0 <service> <release>" >&2
  exit 1
}

[ "$#" -eq 2 ] || usage
SERVICE="$1"
RELEASE="$2"

# Builtins only up to the tool check, so a PATH without coreutils still gets
# the release and tool messages.
SCRIPT_DIR="${BASH_SOURCE[0]%/*}"
[ "$SCRIPT_DIR" != "${BASH_SOURCE[0]}" ] || SCRIPT_DIR=.
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd -P)"
cd "$REPO_ROOT"

REFS="releases/${RELEASE}/source-refs.yaml"
if [ ! -f "$REFS" ]; then
  echo "generate-lock.sh: ${REFS} not found: is '${RELEASE}' a release directory?" >&2
  exit 1
fi

missing=()
for tool in uv nix yq jq; do
  command -v "$tool" >/dev/null 2>&1 || missing+=("$tool")
done
if [ "${#missing[@]}" -gt 0 ]; then
  echo "generate-lock.sh: required tool(s) not on PATH: ${missing[*]}" >&2
  exit 1
fi

REF=$(yq ".\"${SERVICE}\"" "$REFS")
if [ -z "$REF" ] || [ "$REF" = "null" ]; then
  echo "generate-lock.sh: no key '${SERVICE}' in ${REFS}" >&2
  exit 1
fi

shopt -s nullglob
PATCHES=(patches/"${SERVICE}"/"${RELEASE}"/*.patch)

# The lock is resolved from the requirements of the upstream commit, while
# the build installs the patched tree, so a patch that edits them would be
# missing from the lock.
for patch in "${PATCHES[@]}"; do
  if grep -qE '^\+\+\+ b/(test-)?requirements\.txt$' "$patch"; then
    echo "generate-lock.sh: ${patch} edits the requirements, which the lock is resolved without" >&2
    exit 1
  fi
done

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Resolve the tag to its commit and the NAR hash of its tree. The empty cache
# directory keeps nix from answering with an earlier resolution of the
# mutable tag, which it otherwise falls back to when GitHub is unreachable;
# a github: reference needs no flake registry. A failure exits here with
# nix's status and stderr, before anything is written.
PREFETCH=$(XDG_CACHE_HOME="${TMP}/cache" nix --extra-experimental-features 'nix-command flakes' \
  flake prefetch --option flake-registry '' --json "github:openstack/${SERVICE}/${REF}")
REV=$(jq -r '.locked.rev' <<<"$PREFETCH")
HASH=$(jq -r '.hash' <<<"$PREFETCH")
TREE=$(jq -r '.storePath' <<<"$PREFETCH")

# The merge rules are those of the Docker path: the script edits
# releases/<release>/upper-constraints.txt relative to its working directory,
# here a copy of the two files.
mkdir -p "${TMP}/releases/${RELEASE}" "${TMP}/work"
cp "releases/${RELEASE}/upper-constraints.txt" "${TMP}/releases/${RELEASE}/"
if [ -f "overrides/${RELEASE}/constraints.txt" ]; then
  mkdir -p "${TMP}/overrides/${RELEASE}"
  cp "overrides/${RELEASE}/constraints.txt" "${TMP}/overrides/${RELEASE}/"
fi
(cd "$TMP" && bash "${REPO_ROOT}/scripts/apply-constraint-overrides.sh" "$RELEASE" >/dev/null)
MERGED="${TMP}/releases/${RELEASE}/upper-constraints.txt"

# PEP 503 normalisation, for comparing a requirement name with a constraint.
normalize() {
  local name="${1,,}"
  name="${name//_/-}"
  echo "${name//./-}"
}

# A TOML basic string.
toml_str() {
  local s="${1//\\/\\\\}"
  printf '"%s"' "${s//\"/\\\"}"
}

# One indented array element per argument.
toml_items() {
  local item
  for item in "$@"; do
    printf '    %s,\n' "$(toml_str "$item")"
  done
}

declare -A CONSTRAINED=()
CONSTRAINTS=()
while IFS= read -r line; do
  [[ "$line" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*=== ]] || continue
  CONSTRAINED["$(normalize "${line%%===*}")"]=1
  CONSTRAINTS+=("${line/===/==}")
done <"$MERGED"

# The service with its extras, the extra pip packages, and the venv-builder
# pins. A venv-builder package the constraints pin is listed by name only:
# the service build re-pins it through the constraints, as the comment in
# images/venv-builder/requirements.txt describes.
EXTRAS=$(yq -r ".\"${SERVICE}\".pip_extras // [] | join(\",\")" "releases/${RELEASE}/extra-packages.yaml")
DEPENDENCIES=("${SERVICE}${EXTRAS:+[${EXTRAS}]}")
while IFS= read -r pkg; do
  [ -n "$pkg" ] && DEPENDENCIES+=("$pkg")
done < <(yq -r ".\"${SERVICE}\".pip_packages // [] | .[]" "releases/${RELEASE}/extra-packages.yaml")
while IFS= read -r line; do
  [[ "$line" =~ ^([A-Za-z0-9][A-Za-z0-9._-]*)==[^=] ]] || continue
  name="${BASH_REMATCH[1]}"
  if [ -n "${CONSTRAINED[$(normalize "$name")]:-}" ]; then
    DEPENDENCIES+=("$name")
  else
    DEPENDENCIES+=("$line")
  fi
done <images/venv-builder/requirements.txt

# The test group: stestr and testtools, which run the suite, unless the
# service's test-requirements.txt lists them, then that file without
# comments, blank lines and pip options.
TEST_REQS=()
declare -A IN_TEST_REQS=()
if [ -f "${TREE}/test-requirements.txt" ]; then
  while IFS= read -r line; do
    line="${line%%#*}"
    line="${line%"${line##*[![:space:]]}"}"
    line="${line#"${line%%[![:space:]]*}"}"
    [ -z "$line" ] || [[ "$line" == -* ]] && continue
    TEST_REQS+=("$line")
    if [[ "$line" =~ ^([A-Za-z0-9][A-Za-z0-9._-]*) ]]; then
      IN_TEST_REQS["$(normalize "${BASH_REMATCH[1]}")"]=1
    fi
  done <"${TREE}/test-requirements.txt"
fi
TEST_GROUP=()
for runner in stestr testtools; do
  [ -n "${IN_TEST_REQS[$runner]:-}" ] || TEST_GROUP+=("$runner")
done
TEST_GROUP+=("${TEST_REQS[@]}")

{
  echo "# SPDX-FileCopyrightText: Copyright 2026 SAP SE or an SAP affiliate company"
  echo "#"
  echo "# SPDX-License-Identifier: Apache-2.0"
  echo "#"
  echo "# Generated by nix/spike/generate-lock.sh ${SERVICE} ${RELEASE}; regenerate, do not edit."
  echo
  echo "[project]"
  echo "name = $(toml_str "cobaltcore-${SERVICE}-${RELEASE}")"
  echo 'version = "0"'
  echo 'requires-python = "==3.12.*"'
  echo "dependencies = ["
  toml_items "${DEPENDENCIES[@]}"
  echo "]"
  echo
  echo "[dependency-groups]"
  echo "test = ["
  toml_items "${TEST_GROUP[@]}"
  echo "]"
  echo
  echo "[tool.uv]"
  echo "package = false"
  echo "constraint-dependencies = ["
  toml_items "${CONSTRAINTS[@]}"
  echo "]"
  echo
  echo "[tool.uv.sources]"
  echo "${SERVICE} = { git = $(toml_str "https://github.com/openstack/${SERVICE}"), rev = $(toml_str "$REV") }"
} >"${TMP}/work/pyproject.toml"

# A resolution failure exits here with uv's status and output; the trap
# removes the work directory and the committed lock stays as it was.
(cd "${TMP}/work" && UV_PYTHON=3.12 uv lock)

jq -n --arg ref "$REF" --arg rev "$REV" --arg hash "$HASH" \
  '{ref: $ref, rev: $rev, hash: $hash, patches: $ARGS.positional}' --args "${PATCHES[@]}" >"${TMP}/work/sources.json"

# TMP may lie on another filesystem, where mv copies file by file. The copy
# goes to a staging directory beside the lock first, so the move into place
# renames within one filesystem.
DEST="nix/spike/locks/${RELEASE}/${SERVICE}"
mkdir -p "$DEST"
STAGE=$(mktemp -d "${DEST}/.stage.XXXXXX")
trap 'rm -rf "$TMP" "$STAGE"' EXIT
cp "${TMP}/work/pyproject.toml" "${TMP}/work/uv.lock" "${TMP}/work/sources.json" "$STAGE/"
mv "${STAGE}/pyproject.toml" "${STAGE}/uv.lock" "${STAGE}/sources.json" "$DEST/"
echo "generate-lock.sh: wrote ${DEST}"
